const assert = require("node:assert/strict");
const path = require("node:path");

module.exports = async ({ page, read, click, select, skip, confirm, action, output, viewport }) => {
    const pouch = slot => click(92 + slot * 134, 977);
    const preview = () => page.evaluate(() => window.__skillBattlePreview.panel.presenter.selection?.preview);
    const screenshot = name => page.screenshot({ path: path.join(output, `C-${name}-${viewport.width}.png`) });
    let checks = 0;
    await click(136, 108);
    const initial = (await read()).state;
    await pouch(2); await confirm();
    assert.match((await read()).message, /生命已满/);
    assert.deepEqual((await read()).state, initial);
    checks++;
    await select(1); await pouch(0);
    assert.equal((await preview()).durabilityCost, 5);
    assert.equal((await preview()).burnApplied, 2);
    await pouch(1);
    assert.equal((await preview()).blockGained, 4);
    await pouch(1);
    assert.equal((await preview()).durabilityCost, 0);
    await pouch(0); await click(120, 1220);
    assert.deepEqual((await read()).state, initial);
    checks++;
    await select(1); await pouch(0);
    await screenshot("fire-preview");
    await confirm();
    const fire = (await read()).state;
    assert.equal(fire.weaponDurability, 45);
    assert.equal(fire.enemyBurn, 1);
    assert.equal(fire.enemy.hp, 10);
    assert.equal(fire.pouchSlots[0], null);
    await confirm(); await pouch(1);
    assert.deepEqual((await read()).state, fire);
    await page.waitForFunction(() => window.__skillBattlePreview.panel.numbers.text.startsWith("灼烧"));
    await screenshot("fire-feedback");
    await page.evaluate(() => window.__skillBattlePreview.close());
    await page.waitForTimeout(400);
    await page.evaluate(() => window.__skillBattlePreview.reopen());
    assert.deepEqual((await read()).state, fire);
    assert.deepEqual((await read()).display, fire);
    checks += 3;
    await action(1); await action(1);
    assert.equal((await read()).state.phase, "victory");
    const first = (await read()).state;
    await click(360, 674);
    const second = (await read()).state;
    assert.equal(second.encounterId, 2);
    assert.equal(second.player.hp, first.player.hp);
    assert.equal(second.weaponDurability, 45);
    assert.deepEqual(second.pouchSlots, first.pouchSlots);
    await click(360, 674);
    assert.deepEqual((await read()).state, second);
    checks += 2;
    await pouch(2);
    assert.equal((await preview()).healAmount, 12);
    assert.equal((await preview()).playerHpLoss, 7);
    await screenshot("heal-preview");
    await confirm(); await skip();
    const healed = (await read()).state;
    assert.equal(healed.player.hp, 43);
    assert.equal(healed.swordQi, 0);
    assert.equal(healed.pouchSlots[2], null);
    assert.equal(healed.round, 2);
    checks++;
    await action(1);
    await select(1); await pouch(1);
    assert.equal((await preview()).enchantDamage, 6);
    assert.equal((await preview()).blockGained, 4);
    assert.equal((await preview()).playerHpLoss, 10);
    await screenshot("earth-preview");
    await confirm(); await skip();
    assert.equal((await read()).state.player.hp, 33);
    assert.equal((await read()).state.weaponDurability, 40);
    await action(3);
    assert.equal((await read()).state.phase, "victory");
    checks++;
    await click(360, 674);
    let third = (await read()).state;
    assert.equal(third.encounterId, 3);
    assert.equal(third.player.hp, 33);
    assert.equal(third.weaponDurability, 40);
    assert.deepEqual(third.pouchSlots, [null, null, null, null, null]);
    assert.equal(third.swordQi, 0);
    assert.equal(third.enemyBurn, 0);
    await page.evaluate(() => { window.__skillBattlePreview.close(); window.__skillBattlePreview.reopen(); });
    assert.deepEqual((await read()).state, third);
    await screenshot("third-carry");
    checks += 2;
    for (let i = 0; i < 30 && third.phase === "player_input"; i++) {
        const intent = await page.evaluate(() => {
            const p = window.__skillBattlePreview.panel.presenter;
            return p.setup.enemy.intents[p.display.enemyIntentIndex];
        });
        const id = third.swordQi >= 2 ? (intent.interruptible ? 4 : 3) : (intent.damage > 0 ? 2 : 1);
        await action(id);
        third = (await read()).state;
    }
    assert.equal(third.phase, "victory");
    assert.equal(third.player.hp, 33);
    assert.equal(await page.evaluate(() => window.__skillBattlePreview.panel.buttons.continue.visible), false);
    await screenshot("route-cleared");
    checks++;
    await click(584, 855); // Explicit guard new run.
    assert.equal((await read()).state.weaponDurability, 50);
    assert.equal((await read()).state.player.hp, 50);
    assert.equal((await read()).state.pouchSlots.filter(Boolean).length, 3);
    checks++;
    const fixture = async durability => page.evaluate(durability => {
        const { manager, panel } = window.__skillBattlePreview;
        const state = manager.state;
        manager.start(panel.presenter.setup, {
            playerHp: state.player.hp, playerMaxHp: state.player.maxHp,
            weaponId: state.weaponId, weaponDurability: durability, pouchSlots: state.pouchSlots,
        });
        panel.openEncounter(3);
    }, durability);
    await fixture(4);
    const lowDurability = (await read()).state;
    await select(1); await pouch(0); await confirm();
    assert.match((await read()).message, /耐久不足/);
    assert.deepEqual((await read()).state, lowDurability);
    await screenshot("low-durability");
    await click(120, 1220); await select(2); await pouch(0);
    assert.match((await read()).message, /不可注灵/);
    assert.deepEqual((await read()).state, lowDurability);
    checks += 2;
    await fixture(5);
    await select(1); await pouch(0); await confirm(); await skip();
    assert.equal((await read()).state.weaponDurability, 0);
    assert.equal((await read()).state.pouchSlots[0], null);
    await action(1);
    assert.equal((await read()).state.weaponDurability, 0);
    checks++;
    return checks;
};
